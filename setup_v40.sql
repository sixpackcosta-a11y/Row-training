-- Temporada base 2026-27 para los dos equipos ya planificados. Lunes-domingo real.
-- Se crean solo fechas futuras sin sesión existente; el entrenador puede editar todo desde el panel.
do $$
declare d date; wk int; phase text; team text; gymtitle text; ergotitle text; martitle text;
begin
 for team in select unnest(array['veteranas','senior_m']) loop
  d := date '2026-09-01';
  while d <= date '2027-05-31' loop
   wk := floor((d-date '2026-09-01')/7)+1;
   phase := case when d < '2026-11-01' then 'BASE' when d < '2027-01-01' then 'FUERZA' when d < '2027-03-01' then 'TRANSFERENCIA' when d < '2027-04-15' then 'ESPECIFICO' else 'PUESTA A PUNTO' end;
   -- Martes GYM
   if extract(isodow from d)=2 and not exists(select 1 from public.training_sessions s where s.team_code=team and s.session_date=d and s.session_type='GYM') then
    gymtitle := case phase when 'BASE' then 'GYM · Fuerza general' when 'FUERZA' then 'GYM · Fuerza máxima controlada' when 'TRANSFERENCIA' then 'GYM · Fuerza + transferencia' when 'ESPECIFICO' then 'GYM · Mantenimiento de fuerza' else 'GYM · Activación / mantenimiento' end;
    insert into public.training_sessions(team_code,session_date,session_type,title,content) values(team,d,'GYM',gymtitle,'Catálogo principal: sentadilla/prensa · RDL/hip thrust · remo · press · core. Sin llegar al fallo; ajustar volumen según competición y fatiga.');
   end if;
   -- Viernes segundo GYM; Senior puede usar miércoles como tercer día en base/fuerza
   if extract(isodow from d)=5 and not exists(select 1 from public.training_sessions s where s.team_code=team and s.session_date=d and s.session_type='GYM') then
    insert into public.training_sessions(team_code,session_date,session_type,title,content) values(team,d,'GYM','GYM · Fuerza específica','5-6 ejercicios del catálogo. Prioridad piernas/cadena posterior/espalda/core. Reducir volumen en semana de competición.');
   end if;
   if team='senior_m' and d<'2027-02-01' and extract(isodow from d)=3 and not exists(select 1 from public.training_sessions s where s.team_code=team and s.session_date=d and s.session_type='GYM') then
    insert into public.training_sessions(team_code,session_date,session_type,title,content) values(team,d,'GYM','GYM · Complementario','Sesión breve de fuerza/estabilidad sin interferir con el MAR del jueves.');
   end if;
   -- ERGO: Veteranas miércoles; Senior sábado. Progresión por fase.
   if ((team='veteranas' and extract(isodow from d)=3) or (team='senior_m' and extract(isodow from d)=6)) and not exists(select 1 from public.training_sessions s where s.team_code=team and s.session_date=d and s.session_type='ERG') then
    ergotitle := case phase when 'BASE' then 'ERGO · UT2' when 'FUERZA' then 'ERGO · UT1' when 'TRANSFERENCIA' then 'ERGO · UT1-AT' when 'ESPECIFICO' then 'ERGO · AT / calidad' else 'ERGO · Activación / control' end;
    insert into public.training_sessions(team_code,session_date,session_type,title,content) values(team,d,'ERG',ergotitle,'Seleccionar desde Biblioteca ERGO según semana y estado del equipo. Mantener volumen UT2/UT1 durante toda la temporada; introducir AT/TR-AN progresivamente.');
   end if;
   -- MAR jueves y domingo: técnica + salidas + Virada-Ciaboga + ritmo. PPM siempre editable por entrenador.
   if extract(isodow from d) in (4,7) and not exists(select 1 from public.training_sessions s where s.team_code=team and s.session_date=d and s.session_type='MAR') then
    martitle := case phase when 'BASE' then 'MAR · Técnica y base' when 'FUERZA' then 'MAR · Técnica + fuerza por palada' when 'TRANSFERENCIA' then 'MAR · Ritmo + maniobras' when 'ESPECIFICO' then 'MAR · Específico de competición' else 'MAR · Calidad y puesta a punto' end;
    insert into public.training_sessions(team_code,session_date,session_type,title,content) values(team,d,'MAR',martitle,
      case phase
       when 'BASE' then 'Calentamiento · técnica a baja frecuencia · salidas controladas · Virada-Ciaboga · bloque aeróbico · vuelta a la calma. PPM a decisión del entrenador.'
       when 'FUERZA' then 'Calentamiento · técnica · salidas · Virada-Ciaboga · bloques de fuerza por palada/ritmo medio · vuelta a la calma.'
       when 'TRANSFERENCIA' then 'Calentamiento · salidas + aceleración · Virada-Ciaboga · series por tiempo o metros · pirámides de ritmo · vuelta a la calma.'
       when 'ESPECIFICO' then 'Calentamiento · salidas específicas · Virada-Ciaboga a intensidad · series específicas por tiempo/metros · recuperación completa · vuelta a la calma.'
       else 'Volumen reducido · técnica limpia · salidas · Virada-Ciaboga · esfuerzos cortos de calidad. Evitar fatiga residual.' end);
   end if;
   d := d + 1;
  end loop;
 end loop;
end $$;
