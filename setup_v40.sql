create table if not exists public.exercise_library (
 id bigint generated by default as identity primary key,
 category text not null check(category in ('GYM','ERG','MAR')),
 name text not null,
 description text, default_dose text, default_rest text,
 alternatives jsonb not null default '[]'::jsonb,
 image_key text, created_by uuid default auth.uid() references auth.users(id) on delete set null,
 is_active boolean not null default true, created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
 unique(category,name)
);
create table if not exists public.session_blocks (
 id bigint generated by default as identity primary key,
 training_session_id bigint not null references public.training_sessions(id) on delete cascade,
 block_order integer not null default 1,
 library_exercise_id bigint references public.exercise_library(id) on delete set null,
 name text not null, mode text check(mode in ('TIEMPO','METROS','REPETICIONES','LIBRE')) default 'LIBRE',
 amount numeric, unit text, ppm numeric, level text check(level in ('BAJO','MEDIO','ALTO') or level is null),
 recovery text, cue text, created_at timestamptz not null default now()
);
create table if not exists public.session_history (
 id bigint generated by default as identity primary key,
 training_session_id bigint, team_code text not null, session_date date not null, session_type text not null,
 title text not null, snapshot jsonb not null, completed_by uuid references auth.users(id) on delete set null,
 created_at timestamptz not null default now()
);

alter table public.exercise_library enable row level security;
alter table public.session_blocks enable row level security;
alter table public.session_history enable row level security;
grant select,insert,update,delete on public.exercise_library,public.session_blocks,public.session_history to authenticated;
grant usage,select on sequence public.exercise_library_id_seq,public.session_blocks_id_seq,public.session_history_id_seq to authenticated;

drop policy if exists exercise_library_read on public.exercise_library;
create policy exercise_library_read on public.exercise_library for select to authenticated using(is_active or public.is_coach());
drop policy if exists exercise_library_write on public.exercise_library;
create policy exercise_library_write on public.exercise_library for all to authenticated using(public.is_coach()) with check(public.is_coach());
drop policy if exists session_blocks_read on public.session_blocks;
create policy session_blocks_read on public.session_blocks for select to authenticated using(
 exists(select 1 from public.training_sessions s where s.id=training_session_id and (public.is_coach() or s.session_type<>'MAR'))
);
drop policy if exists session_blocks_write on public.session_blocks;
create policy session_blocks_write on public.session_blocks for all to authenticated using(
 exists(select 1 from public.training_sessions s where s.id=training_session_id and public.can_manage_team(s.team_code))
) with check(exists(select 1 from public.training_sessions s where s.id=training_session_id and public.can_manage_team(s.team_code)));
drop policy if exists session_history_read on public.session_history;
create policy session_history_read on public.session_history for select to authenticated using(public.is_coach() or completed_by=auth.uid());
drop policy if exists session_history_write on public.session_history;
create policy session_history_write on public.session_history for insert to authenticated with check(public.is_coach() or completed_by=auth.uid());

